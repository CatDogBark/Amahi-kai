class DnsAlias < ApplicationRecord

  after_save :restart
  after_destroy :restart

  scope :user_visible,->{where(["address != ?", ''])}

  validates :name, presence: true, uniqueness: true, format: { with: /\A[a-z][a-z0-9-]*\z/i }

  protected

  def restart
    regenerate_dnsmasq_config
    reload_dnsmasq
  end

  private

  def regenerate_dnsmasq_config
    lines = ["# Auto-generated by Amahi-kai — do not edit manually"]
    DnsAlias.all.each do |a|
      if a.address.present?
        lines << "address=/#{a.name}/#{a.address}"
      else
        lines << "address=/#{a.name}/"
      end
    end

    Privileged.call('network.write_dns_aliases', content: lines.join("\n") + "\n")
  rescue Privileged::Error => e
    # The alias is saved; the file catches up the next time an alias changes.
    Rails.logger.error("DnsAlias: dnsmasq aliases not written: #{e.message}")
  end

  def reload_dnsmasq
    DnsmasqService.restart!
  end

end
